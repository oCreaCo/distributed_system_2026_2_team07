"""Validate the CEGAS test suite with tcopt's V0-V4 checks and write the run config.

  PYTHONPATH=$TCOPT skydiscover/.venv/bin/python adrs/dtfm_placement/cegas/prepare.py \
      --reference <best_program.py> [--panel output/cegas_panel] [--runs 'output/pilot_*' 'output/main_*']

  V0 isolation audit of measure.py; V1 the reference is valid on the tests; V2 the suite ranks stored
  programs (checkpoints of earlier SkyDiscover runs, with their official combined_score) like the official
  evaluator, Spearman >= 0.6 over >= 10 unique programs; V3 tolerance from two reference repeats;
  V4 some test separates the initial program from the reference.
Writes <panel>/validation.json, updates panel.json, and writes cegas/config.yaml pinned to both hashes.
"""
import argparse
import asyncio
import glob
import hashlib
import json
import os
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
TASK_DIR = HERE.parent
TCOPT = os.environ.get("TCOPT", "/home/yeomjy/TCResearch/tcopt")
sys.path.insert(0, TCOPT)
from tcopt.common.autopanel.checker import AutoPanelChecker, digest  # noqa: E402
from tcopt.common.autopanel.validate import validate_panel  # noqa: E402


def stored_programs(patterns, exclude_sha):
    """Every evaluated program in the latest checkpoint of each run (one record per unique code)."""
    out, seen = [], set(exclude_sha)
    for pattern in patterns:
        for run in sorted(glob.glob(str(TASK_DIR / pattern))):
            cps = sorted(glob.glob(f"{run}/checkpoints/checkpoint_*"), key=lambda p: int(p.rsplit("_", 1)[1]))
            if not cps:
                continue
            for path in sorted(glob.glob(f"{cps[-1]}/programs/*.json")):
                data = json.load(open(path))
                code, score = data.get("solution"), (data.get("metrics") or {}).get("combined_score")
                if not isinstance(code, str) or not isinstance(score, (int, float)) or score <= 0:
                    continue
                sha = hashlib.sha256(code.encode()).hexdigest()
                if sha in seen:
                    continue
                seen.add(sha)
                out.append(dict(path=path, code=code, official_score=float(score), role="stored", run=os.path.basename(run)))
    return out


def write_config(panel_dir, validation_sha, panel_sha, out, requests, evals):
    base = yaml.safe_load(open(TASK_DIR / "config.yaml"))
    cfg = {k: base[k] for k in ("language", "diff_based_generation", "max_solution_length", "llm")}
    cfg["prompt"] = {"system_message": base["prompt"]["system_message"]}
    cfg.update(max_iterations=evals, checkpoint_interval=5, log_level="INFO",
               evaluator={"timeout": 900, "cascade_evaluation": False, "max_retries": 0})
    # Paper setting (advice_editeval): suite results are advice only, edits may request evaluation.
    cfg["search"] = {"type": "q_editeval", "database": dict(
        panel_source="autopanel", adrs_task="dtfm_placement", autopanel_dir=str(panel_dir),
        autopanel_validation_sha256=validation_sha, autopanel_panel_sha256=panel_sha,
        reference_source="baseline", reference_scale=1.0, gate_release_after_requests=0,
        check_refusals=3, check_deadline_s=300, stop_at=None, max_requests=requests,
        eval_reserve_s=120, wall_limit_s=4 * 3600, rundraft_total=0)}
    text = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True)
    # keep the key out of the file: SkyDiscover expands ${VAR} when it loads the config
    text = re.sub(r"api_key: .*", "api_key: ${OPENROUTER_COURSE_PROJECT_KEY}", text)
    Path(out).write_text("# GENERATED by cegas/prepare.py; CEGAS (tcopt q_editeval, advice + edit=evaluate)\n" + text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reference", required=True, help="reference program: best program of a baseline optimizer run")
    ap.add_argument("--panel", default=str(TASK_DIR / "output" / "cegas_panel"))
    ap.add_argument("--runs", nargs="+", default=["output/pilot_*", "output/main_*"])
    ap.add_argument("--config-out", default=str(HERE / "config.yaml"))
    ap.add_argument("--requests", type=int, default=100, help="LLM call budget")
    ap.add_argument("--evals", type=int, default=100, help="official evaluation cap")
    a = ap.parse_args()
    panel_dir = Path(a.panel).resolve()
    initial, reference = TASK_DIR / "initial_program.py", Path(a.reference).resolve()
    exclude = {hashlib.sha256(p.read_text().encode()).hexdigest() for p in (initial, reference)}
    programs = stored_programs(a.runs, exclude)
    print(f"{len(programs)} unique stored programs from {sorted({p['run'] for p in programs})}")
    report = asyncio.run(validate_panel(panel_dir / "panel.json", str(initial), str(reference), programs,
                                        python=json.load(open(panel_dir / "panel.json"))["python"]))
    v2 = report.get("V2", {})
    print(json.dumps(dict(passed=report["passed"], reasons=report["reasons"], tol=report.get("tol"),
                          V2_spearman=v2.get("spearman"), V2_n=v2.get("n_stored_unique"),
                          V4=report.get("V4", {}).get("distinguishing_inputs")), indent=1))
    if not report["passed"]:
        return 1
    validation_sha = digest(panel_dir / "validation.json")
    panel_sha = AutoPanelChecker(panel_dir / "panel.json", panel_dir / "validation_runs").fingerprint()
    write_config(panel_dir, validation_sha, panel_sha, a.config_out, a.requests, a.evals)
    print(f"validation sha {validation_sha}\npanel sha {panel_sha}\nwrote {a.config_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
